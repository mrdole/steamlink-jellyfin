#!/usr/bin/env bash
# Build the on-TV Jellyfin app for the Steam Link.   scripts/build-app.sh  ->  out/app/jellyfin/
#   sljf-ui (Qt 5.14 Quick host, SDK qmake), main.qml, theme.js (from themes/<theme>.yaml, THEME=name),
#   fonts (the theme's font, copied from this machine), toc.txt + icon.png (the tile), run.sh.
# Install on the Link: scripts/deploy.sh (copies it to /home/apps/jellyfin).
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
REPO=$HERE
SDK=${SDK:-$HOME/steamlink-sdk}
THEME=${THEME:-gruvbox}
OUT=$HERE/out/app/jellyfin
B=$SDK/build-sljf/app; mkdir -p "$B" "$OUT/fonts"

python3 - "$REPO/themes/$THEME.yaml" "$OUT/theme.js" <<'PY'
import json, sys, yaml
t = yaml.safe_load(open(sys.argv[1]))
open(sys.argv[2], "w").write("// generated by build-app.sh from themes/%s: do not edit\n.pragma library\nvar C = %s\nvar FONT = %s\n"
                             % (sys.argv[1].rsplit("/", 1)[1], json.dumps(t["palette"], indent=1), json.dumps(t["font"])))
PY
FONT=$(python3 -c "import yaml,sys;print(yaml.safe_load(open(sys.argv[1]))['font'])" "$REPO/themes/$THEME.yaml")
for style in Regular Bold; do
  f=$(fc-match -f '%{file}' "$FONT:style=$style")
  cp "$f" "$OUT/fonts/"
done

( set +u; source "$SDK/setenv.sh" >/dev/null; set -u
  cd "$B" && qmake "$HERE/app/app.pro" >/dev/null && make -j"$(nproc)" 2>&1 | grep -E "error|warning: unused" || true
  [ -f "$B/sljf-ui" ] || { echo "sljf-ui build failed"; exit 1; }
  "$STRIP" -o "$OUT/sljf-ui" "$B/sljf-ui" )
cp "$HERE/app/main.qml" "$HERE/app/toc.txt" "$HERE/app/run.sh" "$OUT/"
C() { python3 -c "import yaml,sys;print(yaml.safe_load(open(sys.argv[1]))['palette'][sys.argv[2]])" "$REPO/themes/$THEME.yaml" "$1"; }
magick -size 116x116 "xc:$(C card)" -fill "$(C accent)" -draw "rectangle 0,0 115,7" \
  -fill "$(C accent)" -draw "polygon 40,34 40,86 86,60" -fill "$(C fg)" -font "$OUT/fonts/$(ls "$OUT/fonts" | grep -i bold | head -1)" \
  -pointsize 13 -gravity south -annotate +0+6 "JELLYFIN" "$OUT/icon.png"
ls -l "$OUT" "$OUT/fonts"
